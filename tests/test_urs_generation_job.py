def test_generate_batch_retries_on_max_tokens_truncation_then_succeeds(db_path, isolated_gateway):
    urs = _make_urs()
    calls = []

    def fake_gemini(contents, config):
        calls.append(1)
        if len(calls) == 1:
            return _FakeResponse(
                '[{"section": "Functional Requirements", "requirement": "cut off',
                finish_reason=types.FinishReason.MAX_TOKENS,
            )
        return _FakeResponse(_req_json("Functional Requirements"))

    _register(isolated_gateway, "gemini", fake_gemini)
    _register(isolated_gateway, "nemotron", _refuse("nemotron"))

    reqs, note = gen_job._generate_batch_resilient(urs["id"], 1, 1, urs, ["Functional Requirements"])

    # MAX_TOKENS truncation is a *content* problem on a call the gateway
    # completed successfully (no exception) — this is entirely layer-3
    # (URS-level) retry, invisible to and unaffected by the gateway's own
    # retry/fallback (which only ever fires on a raised exception).
    assert len(calls) == 2  # retried once after the MAX_TOKENS truncation
    assert note is None     # second attempt parsed cleanly, no fallback needed
    assert len(reqs) == 1


