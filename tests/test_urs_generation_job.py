"""
tests/test_urs_generation_job.py — Regression tests for background URS AI
generation (services/urs_generation_job.py).

Root cause under test: routes/urs.py's /generate endpoint used to iterate
generate_content_stream() *inside* the Flask request, holding a gunicorn
worker for the whole generation time. On large section selections this
exceeded Render's `--timeout=60` and the worker was SIGKILLed mid-stream
([CRITICAL] WORKER TIMEOUT). These tests assert the new behavior instead:
submit_generation_job() returns immediately no matter how long the AI call
takes, progress/results are visible by polling SQLite, one bad batch never
loses requirements already generated by other batches, and — per a
follow-up hardening pass — malformed/truncated output is retried and
salvaged rather than failing the batch outright, while genuine API errors
and safety blocks are never retried at this layer.

Stage 2 (AI Gateway migration): _generate_batch() now calls
pharmagpt.providers.router.generate_content(TaskIntent.URS, ...) instead of
a module-level gemini_client, so these tests inject fake provider responses
by registering fake providers with the router (isolated per test — see
isolated_gateway below) instead of monkeypatching gen_job.gemini_client
directly. Every test that registers a "gemini" fake also registers (or
explicitly refuses) a "nemotron" fake, since the gateway will now try the
opposite provider on a fallback-eligible failure — this keeps each test's
outcome deterministic regardless of whether a real NVIDIA_API_KEY happens
to be set in the environment running the suite.
"""

import json
import time

import pytest
from google.genai import errors as genai_errors

from pharmagpt import urs_database as udb
from pharmagpt.providers import router as ai_router
from pharmagpt.services import urs_generation_job as gen_job
from google.genai import types


class _FakeModels:
    def __init__(self, fn):
        self._fn = fn

    def generate_content(self, *, model=None, contents=None, config=None):
        return self._fn(contents, config)


class _FakeClient:
    def __init__(self, fn):
        self.models = _FakeModels(fn)


class _FakeUsage:
    def __init__(self, prompt_tokens=100, response_tokens=200):
        self.prompt_token_count = prompt_tokens
        self.candidates_token_count = response_tokens


class _FakeCandidate:
    def __init__(self, finish_reason=types.FinishReason.STOP):
        self.finish_reason = finish_reason


class _FakeResponse:
    def __init__(self, text, prompt_tokens=100, response_tokens=200, finish_reason=types.FinishReason.STOP):
        self.text = text
        self.usage_metadata = _FakeUsage(prompt_tokens, response_tokens)
        self.candidates = [_FakeCandidate(finish_reason)]


@pytest.fixture()
def isolated_gateway(isolated_ai_gateway, monkeypatch):
    """conftest.py's isolated_ai_gateway plus the specific provider defaults
    this file's tests rely on, explicit rather than ambient — matches
    tests/test_provider_router.py's own isolated_router convention of
    pinning DEFAULT_CHAT_PROVIDER/DEFAULT_DOCUMENT_PROVIDER/ENABLE_FALLBACK
    rather than depending on whatever pharmagpt/config.py currently
    defaults to."""
    monkeypatch.setattr(isolated_ai_gateway, "DEFAULT_DOCUMENT_PROVIDER", "gemini")
    monkeypatch.setattr(isolated_ai_gateway, "ENABLE_FALLBACK", True)
    return isolated_ai_gateway


def _register(rt, name, fn, model="fake-model"):
    """Register a fake provider under `name`; fn(contents, config) plays
    the role of that provider's response (return a _FakeResponse) or
    failure (raise) for one call."""
    rt.register_provider(name, lambda: _FakeClient(fn), model=model)


def _refuse(name):
    """A fake provider that must never be called — registering this proves
    a happy-path (or already-classified-non-fallback-eligible) call never
    triggers a fallback attempt it doesn't need."""
    def _fn(contents, config):
        raise AssertionError(f"{name} should not have been called")
    return _fn


def _make_urs():
    return udb.create_urs({
        "title": "URS - Autoclave", "equipment_name": "Autoclave-01",
        "equipment_type": "Autoclave", "category": "Equipment",
    }, company_id="test-company-1")


def _req_json(section):
    return json.dumps([{
        "section": section, "requirement": "The system shall do X.",
        "rationale": "GMP", "priority": "High", "gmp_criticality": "GMP-Critical",
        "regulatory_ref": "21 CFR Part 11", "verification_method": "Functional Test",
        "acceptance_criteria": "Pass/fail",
    }])


def _wait_for_terminal_generation(urs_id, timeout=10.0):
    deadline = time.monotonic() + timeout
    status = None
    while time.monotonic() < deadline:
        status = udb.get_generation_status(urs_id)
        if status["generation_status"] in ("completed", "failed"):
            return status
        time.sleep(0.05)
    pytest.fail(f"generation job never reached a terminal status: {status}")


def test_submit_generation_job_returns_immediately_and_completes_in_background(db_path, isolated_gateway):
    urs = _make_urs()

    def fake_generate_content(contents, config):
        time.sleep(0.05)  # simulated network latency, kept small for test speed
        return _FakeResponse(_req_json("Functional Requirements"))

    _register(isolated_gateway, "gemini", fake_generate_content)
    _register(isolated_gateway, "nemotron", _refuse("nemotron"))  # happy path never falls back

    start = time.monotonic()
    gen_job.submit_generation_job(urs["id"], urs, ["Functional Requirements", "Safety Requirements"])
    submit_elapsed = time.monotonic() - start

    # The whole point of this redesign: submitting must not block on the AI call.
    assert submit_elapsed < 0.5

    # Default URS_GENERATION_BATCH_SIZE (2) puts both sections in one batch.
    status = udb.get_generation_status(urs["id"])
    assert status["generation_status"] == "running"
    assert status["generation_progress_total"] == 1

    final = _wait_for_terminal_generation(urs["id"])
    assert final["generation_status"] == "completed"
    assert final["generation_result_count"] == 1

    saved = udb.get_requirements(urs["id"])
    assert len(saved) == 1
    assert saved[0]["section"] == "Functional Requirements"
    assert saved[0]["req_id"]  # numbered by section prefix

    # The fake only ever returns "Functional Requirements" content, so
    # section-coverage tracking should correctly report Safety as missing
    # even though the batch itself didn't raise.
    assert final["generation_message"] == (
        "1 of 2 sections generated successfully (1 requirements). "
        "1 section failed and can be retried: Safety Requirements."
    )


def test_run_generation_job_continues_after_one_batch_fails(db_path, isolated_gateway):
    urs = _make_urs()

    def fake_gemini(contents, config):
        prompt_text = contents[0].parts[0].text
        if "Safety Requirements" in prompt_text:
            raise genai_errors.ServerError(503, {"message": "backend unavailable", "status": "UNAVAILABLE"})
        return _FakeResponse(_req_json("Functional Requirements"))

    def fake_nemotron(contents, config):
        # Both providers genuinely down for the Safety batch — the gateway
        # is fully exhausted, not just Gemini, so that batch truly fails
        # end-to-end rather than silently succeeding via fallback.
        prompt_text = contents[0].parts[0].text
        if "Safety Requirements" in prompt_text:
            raise genai_errors.ServerError(503, {"message": "backend unavailable", "status": "UNAVAILABLE"})
        raise AssertionError("nemotron should not be called for the Functional Requirements batch")

    _register(isolated_gateway, "gemini", fake_gemini)
    _register(isolated_gateway, "nemotron", fake_nemotron)

    batches = [["Functional Requirements"], ["Safety Requirements"]]
    gen_job._run_generation_job(urs["id"], urs, batches)

    status = udb.get_generation_status(urs["id"])
    # One batch succeeded — the job is "completed" (failure surfaced via
    # generation_error / generation_message) rather than discarding the
    # partial result.
    assert status["generation_status"] == "completed"
    assert status["generation_result_count"] == 1
    assert "Batch 2" in status["generation_error"]
    assert status["generation_message"] == (
        "1 of 2 sections generated successfully (1 requirements). "
        "1 section failed and can be retried: Safety Requirements."
    )

    saved = udb.get_requirements(urs["id"])
    assert len(saved) == 1
    assert saved[0]["section"] == "Functional Requirements"


